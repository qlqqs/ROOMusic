"""自主生成 2s 线性相位 FIR；运行：uv run --python 3.12 scripts/dspgen/src2s.py。

只使用任务设计 §2.3 的规格约束，不读取任何参考稿或参考系数。
工具固定为 CPython 3.12、NumPy 2.2.6、SciPy 1.15.3 自带的 HiGHS。
"""
from pathlib import Path
import subprocess
import time

import numpy as np
import scipy
from scipy.optimize import linprog


def basis(x, length, count):
    a = 2 * np.cos(np.pi * np.outer(x, np.arange(count)) / length)
    a[:, 0] = 1
    return a


def generate(length):
    count = length * 19 // 2 + 1
    passing = basis(np.linspace(0, 0.113, 8 * count), length, count)
    stopping = basis(np.linspace(0.99, length, 8 * count), length, count)
    rows = np.vstack((passing, -passing, stopping, -stopping))
    slack = np.r_[np.zeros(2 * len(passing)), -np.ones(2 * len(stopping))]
    upper = np.r_[np.full(len(passing), 1.0001),
                  np.full(len(passing), -0.9999), np.zeros(2 * len(stopping))]
    objective = np.zeros(count + 1)
    objective[-1] = 1
    result = linprog(
        objective, A_ub=np.column_stack((rows, slack)), b_ub=upper,
        A_eq=np.column_stack((basis([0.4758], length, count), [0])), b_eq=[0.5],
        bounds=[(None, None)] * count + [(0, None)], method="highs",
        options={"primal_feasibility_tolerance": 1e-10,
                 "dual_feasibility_tolerance": 1e-10},
    )
    if not result.success:
        raise RuntimeError(f"L={length}: {result.message}")
    center = result.x[:-1]
    h = np.r_[center[:0:-1], center]
    h /= h.sum()
    return h


def metrics(h, length):
    nfft = max(1 << 20, 1 << (16 * len(h) - 1).bit_length())
    response = np.abs(np.fft.rfft(h, nfft))
    x = np.arange(len(response)) * (2 * length / nfft)
    db = 20 * np.log10(np.maximum(response, 1e-300))
    ripple = np.max(np.abs(db[x <= 0.113]))
    stop = -np.max(db[x >= 0.99])
    cutoff = np.interp(0.5, response[::-1], x[::-1])
    # 用首次越过阈值描述过渡带；不把通带波纹当作带边。
    crossings = [x[np.flatnonzero(db <= level)[0]] for level in (-3, -6, -160)]
    if ripple > 0.002 or stop < 160 or abs(cutoff - 0.4758) > 0.002:
        raise RuntimeError(f"L={length}: 规格不满足，纹波={ripple}, 阻带={stop}")
    return ripple, stop, cutoff, crossings


def main():
    if np.__version__ != "2.2.6" or scipy.__version__ != "1.15.3":
        raise RuntimeError("请通过固定依赖的 uv run 入口运行")
    lines = ["// Code generated by scripts/dspgen/src2s.py; DO NOT EDIT.",
             "// 自主线性规划产物；NumPy 2.2.6、SciPy 1.15.3（内置 HiGHS）。",
             "// 方法与复现命令见 scripts/dspgen/README.md；不读取参考系数。",
             "package src", "", "// 从中心向右存半核，含中心点。", "var stage2Half = map[int][]float64{"]
    for length in (2, 4, 8, 16, 32, 64):
        start = time.monotonic()
        h = generate(length)
        ripple, stop, cutoff, crossings = metrics(h, length)
        print(f"L={length}: 通带偏差={ripple:.8f} dB, 阻带={stop:.4f} dB, "
              f"半幅点={cutoff:.8f}, -3/-6/-160 dB={crossings}, "
              f"耗时={time.monotonic()-start:.2f}s", flush=True)
        lines.append(f"\t// L={length}：通带偏差 {ripple:.8f} dB；阻带 {stop:.4f} dB；半幅点 x={cutoff:.8f}。")
        lines.append(f"\t{length}: {{")
        for value in h[len(h)//2:]:
            lines.append(f"\t\t{value:.17g},")
        lines.append("\t},")
    lines.append("}")
    output = Path(__file__).resolve().parents[2] / "backend/internal/dsp/src/kernels2s_gen.go"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    subprocess.run(["gofmt", "-w", str(output)], check=True)


if __name__ == "__main__":
    main()
