// 独立离线生成器：Legendre 零点、Butterworth 初值、受约束极点优化、QR 实现。
// 仅按任务 design §2 的公开方法生成，不读取参考稿或参考系数。
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"math"
	"os"
	"sort"
	"sync"
	"time"
)

type result struct {
	alg, index, n, rate             int
	p                               poles
	a, g                            vector
	constraint                      constraint
	noise, peak, norm, impulseError float64
	stable                          int
}

var algorithmNames = [...]string{"Order5", "Order7", "Clans5", "Clans7"}

type group struct {
	b          *problem
	start      poles
	candidates []result
}

func constraints(alg int) []constraint {
	if alg >= 2 {
		return []constraint{{1.6, 4}, {1.65, 3.8}, {1.8, 3.4}, {2, 3.4}}
	}
	var grid []constraint
	for l := 38; l <= 46; l++ {
		grid = append(grid, constraint{1.5, float64(l) / 10})
	}
	return grid
}

func generateCandidate(alg, index int, b *problem, start poles, c constraint) (result, error) {
	p := b.optimize(start, c)
	a, err := realize(b.n, b.g, p)
	if err != nil {
		return result{}, err
	}
	if alg >= 2 {
		cost := func(p poles) float64 {
			if !p.valid() {
				return 1e9
			}
			a, err := realize(b.n, b.g, p)
			if err != nil {
				return 1e9
			}
			noise, _ := b.spectrum(p)
			stable := b.stability(a, 56)
			return noise + 30*float64(56-stable)
		}
		p = minimize(p, cost, 2500, true)
		a, err = realize(b.n, b.g, p)
		if err != nil {
			return result{}, err
		}
	}
	noise, peak := b.spectrum(p)
	r := result{alg: alg, index: index, n: b.n, rate: b.rate, p: p, a: a, g: b.g, constraint: c, noise: noise, peak: peak, norm: impulseNorm(b.n, b.g, p)}
	fmt.Fprintf(os.Stderr, "%s DSD%d 起点 h=%.2f l=%.1f：噪声 %.3f dB H∞ %.6f ‖h‖₁ %.6f\n", algorithmNames[alg], 64<<index, c.h, c.l, noise, peak, r.norm)
	return r, nil
}

func selectResult(alg, index int, g *group) (result, error) {
	candidates := g.candidates
	sort.SliceStable(candidates, func(i, j int) bool { return candidates[i].noise < candidates[j].noise })
	target := 60
	if alg >= 2 {
		target = 56
	}
	bestStable := 44
	for _, r := range candidates {
		stable := g.b.stability(r.a, target)
		if stable > bestStable {
			bestStable = stable
		}
		if stable < target {
			continue
		}
		r.stable = g.b.stability(r.a, 85)
		var err error
		r.impulseError, err = verifyRealization(r.n, r.a, r.g, r.p)
		if err != nil {
			return result{}, err
		}
		if !r.p.valid() {
			return result{}, fmt.Errorf("极点半径越界")
		}
		return r, nil
	}
	return result{}, fmt.Errorf("%s DSD%d 没有稳定至 %.2f 的候选，实测最高 %.2f", algorithmNames[alg], 64<<index, float64(target)/100, float64(bestStable)/100)
}

func writeOutput(path string, results [4][4]result) error {
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go generate; DO NOT EDIT.")
	fmt.Fprintln(&out, "// 生成命令（仓库根目录）：(cd backend && go run ./internal/dsp/sdm/internal/gen -out internal/dsp/sdm/coeffs_gen.go -jobs 8)")
	fmt.Fprintln(&out, "// 耗时量级：约 1 小时；2026-11-09 本机 8 并发实测 55 分 13 秒。")
	fmt.Fprintln(&out, "\npackage sdm")
	fmt.Fprintln(&out, "\n// 系数由 internal/gen 自主生成；仿真使用延迟输入，幅度为内部调制器输入。")
	fmt.Fprintln(&out, "var generatedCoefficients = [4][4]coefficients{")
	for alg := range results {
		fmt.Fprintf(&out, " // %s\n {\n", algorithmNames[alg])
		for _, r := range results[alg] {
			maxRadius := 0.0
			for _, z := range r.p.roots() {
				maxRadius = math.Max(maxRadius, math.Hypot(real(z), imag(z)))
			}
			fmt.Fprintf(&out, "// DSD%d：约束起点 h=%.2f l=%.1f；H∞=%.9f，‖h‖₁=%.9f，带内噪声=%.6f dB，稳定上限=%.2f。\n", r.rate/44100, r.constraint.h, r.constraint.l, r.peak, r.norm, r.noise, float64(r.stable)/100)
			fmt.Fprintf(&out, "// 最大极点半径=%.9f；16384 点冲激最大误差=%.3g。\n", maxRadius, r.impulseError)
			fmt.Fprintf(&out, "{order:%d,a:[7]float64{", r.n)
			for i := 0; i < r.n; i++ {
				fmt.Fprintf(&out, "%.17g,", r.a[i])
			}
			fmt.Fprint(&out, "},g:[7]float64{")
			for i := 0; i < r.n; i++ {
				fmt.Fprintf(&out, "%.17g,", r.g[i])
			}
			fmt.Fprintln(&out, "}},")
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0644)
}

func main() {
	out := flag.String("out", "coeffs_gen.go", "生成的 Go 文件")
	jobs := flag.Int("jobs", 4, "同时优化的约束起点数")
	flag.Parse()
	if *jobs < 1 {
		fmt.Fprintln(os.Stderr, "jobs 必须为正数")
		os.Exit(1)
	}
	start := time.Now()
	var groups [4][4]*group
	for alg := range groups {
		for index := range groups[alg] {
			n := 5
			if alg%2 == 1 {
				n = 7
			}
			b := newProblem(n, 44100*(64<<index))
			groups[alg][index] = &group{b: b, start: b.butterworth(), candidates: make([]result, len(constraints(alg)))}
		}
	}
	type job struct {
		alg, index, candidate int
		constraint            constraint
	}
	queue := make(chan job)
	var wg sync.WaitGroup
	var firstErr error
	var mu sync.Mutex
	for w := 0; w < *jobs; w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := range queue {
				g := groups[j.alg][j.index]
				r, err := generateCandidate(j.alg, j.index, g.b, g.start, j.constraint)
				if err != nil {
					mu.Lock()
					if firstErr == nil {
						firstErr = err
					}
					mu.Unlock()
					fmt.Fprintln(os.Stderr, err)
					continue
				}
				g.candidates[j.candidate] = r
			}
		}()
	}
	// 高倍率起点优先；任务各写独立槽位，调度顺序不影响数值结果。
	for index := 3; index >= 0; index-- {
		for alg := 3; alg >= 0; alg-- {
			for candidate, c := range constraints(alg) {
				queue <- job{alg, index, candidate, c}
			}
		}
	}
	close(queue)
	wg.Wait()
	if firstErr != nil {
		fmt.Fprintln(os.Stderr, "生成失败：", firstErr)
		os.Exit(1)
	}
	var results [4][4]result
	for alg := range results {
		for index := range results[alg] {
			r, err := selectResult(alg, index, groups[alg][index])
			if err != nil {
				fmt.Fprintln(os.Stderr, "生成失败：", err)
				os.Exit(1)
			}
			results[alg][index] = r
			fmt.Fprintf(os.Stderr, "完成 %s DSD%d：噪声 %.3f dB 稳定上限 %.2f\n", algorithmNames[alg], 64<<index, r.noise, float64(r.stable)/100)
		}
	}
	if err := writeOutput(*out, results); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "生成 %s，用时 %s\n", *out, time.Since(start).Round(time.Second))
}
